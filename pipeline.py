def keyword_scores(tfidf_matrix):

    word_importance = np.asarray(
        tfidf_matrix.mean(axis=0)
    ).ravel()

    sentence_keyword_scores = (
        tfidf_matrix @ word_importance
    )

    return sentence_keyword_scores

