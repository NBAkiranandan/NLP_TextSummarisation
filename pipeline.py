def is_metadata_sentence(sentence):

    text = sentence.strip()

    # Empty sentence
    if not text:
        return True

    # Standalone source/byline
    if re.fullmatch(
        r"(associated press|reuters|afp|cnn|bbc)",
        text,
        flags=re.IGNORECASE
    ):
        return True

    # Standalone time/date metadata
    if re.search(r"\b\d{1,2}:\d{2}\b", text):
        return True

    # Date containing a year
    if re.search(r"\b(19|20)\d{2}\b", text):
        return True

    return False

def preprocess_article(article):

    original_sentences = sent_tokenize(article)

    sentence_data = []

    for sentence in original_sentences:

        # Remove obvious metadata/noise
        if is_metadata_sentence(sentence):
            continue

        # Preprocess remaining sentence
        processed = preprocess_sentence(sentence)

        # Remove sentences that become empty
        if not is_valid_sentence(processed):
            continue

        sentence_data.append({
            "original": sentence,
            "processed": processed
        })

    return sentence_data

def remove_special_characters(text):

    text = re.sub(
        r"[^a-zA-Z\s]",
        " ",
        text
    )

    text = re.sub(
        r"\s+",
        " ",
        text
    )

    return text.strip()

def remove_stopwords(words):

    return [
        word
        for word in words
        if word not in stop_words
    ]

def preprocess_sentence(sentence):

    # Normalize text
    normalized = normalize_text(sentence)

    # Remove special characters
    cleaned = remove_special_characters(normalized)

    # Tokenize words
    words = word_tokenize(cleaned)

    # Remove stopwords
    filtered_words = remove_stopwords(words)

    # Lemmatize words with POS tagging
    lemmas = []
    for word in filtered_words:
        tag = pos_tag([word])[0][1]
        lemma = lemmatizer.lemmatize(
            word,
            get_wordnet_pos(tag)
        )
        lemmas.append(lemma)

    return " ".join(lemmas)

